"""Core data models across all Narezka stages.

Conforms to section 11 of TZ_Narezka.md.
"""

from __future__ import annotations

from typing import Any, Literal

from pydantic import BaseModel, Field

# Re-export Word, Segment, SpeechSegment


class Event(BaseModel):
    """Discrete highlight event detected by any stage (audio, vision, chat, lexicon, etc.)."""

    id: str
    source: str  # "killfeed" | "sfx" | "audio_tagger" | "loudness" | "chat" | "lexicon" | "semantic" | "twitch_clip"
    type: str  # "kill" | "death" | "multikill" | "laughter" | "scream" | "loud_burst" | "chat_spike" | "chat_laughter" | "hype_phrase" | "semantic_flag" | "game_voice_line"
    start: float  # seconds from VOD start
    end: float  # seconds from VOD start
    score: float = Field(ge=0.0, le=1.0)  # normalized confidence / intensity 0..1
    payload: dict[str, Any] = Field(default_factory=dict)


class Candidate(BaseModel):
    """Candidate highlight window generated by timeline fusion before judging."""

    id: str
    start: float  # window start in seconds
    end: float  # window end in seconds
    peak: float  # point of maximum interest S(t) in seconds
    signal_score: float  # peak S(t) or fused signal intensity
    suspected_categories: list[str] = Field(default_factory=list)
    event_ids: list[str] = Field(default_factory=list)
    features_summary: dict[str, float] = Field(default_factory=dict)  # max values of features in window


class Moment(BaseModel):
    """Final highlight clip moment ready for render and reporting."""

    id: str
    candidate_id: str
    category: Literal["multikill", "epic_play", "funny_joke", "funny_reaction", "fail", "other"]
    title: str
    reason: str
    start: float  # seconds
    end: float  # seconds
    peak: float  # seconds
    judge_score: int = Field(ge=0, le=10)
    confidence: float = Field(ge=0.0, le=1.0)
    final_score: float  # alpha * judge_score/10 + (1 - alpha) * signal_score
    evidence: dict[str, Any] = Field(default_factory=dict)  # quotes, events, signals
    flags: list[str] = Field(default_factory=list)  # "ungrounded", "rule_based", "fast_cut"
    clip_path: str | None = None


class VodMeta(BaseModel):
    """Metadata of the analyzed VOD file."""

    path: str
    duration_s: float
    sha1_head: str


class RunMeta(BaseModel):
    """Execution run metadata."""

    app_version: str = "0.1.0"
    config_hash: str
    asr_backend: str = "faster_whisper"
    judge_model: str = "rule_based_draft"
    cost_usd: float = 0.0
    finished_at: str


class MomentsDocument(BaseModel):
    """Root JSON structure for moments.json as specified in TZ section 11.3."""

    schema_version: str = "1.0"
    vod: VodMeta
    run: RunMeta
    moments: list[Moment] = Field(default_factory=list)
